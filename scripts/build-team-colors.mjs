// Bakes lib/team-colors.generated.ts from nflverse's teams release.
//
// Colours for every table, logos for scoreboards. This ran on colours alone
// until 2026-09-30, on the grounds that team marks are trademarks (the same
// reason the course covers are drawn). The decision that day was that a
// scoreboard without crests reads as a spreadsheet, so the ESPN logo URL
// nflverse lists is kept and shown on score tiles only — hotlinked from its
// source, never proxied through our domain. Results grids keep the swatch.
//
// Usage: node scripts/build-team-colors.mjs

import { writeFile } from "node:fs/promises";
import { parse } from "csv-parse/sync";

const URL =
  "https://github.com/nflverse/nflverse-data/releases/download/teams/teams_colors_logos.csv";

const res = await fetch(URL);
if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${URL}`);

const rows = parse(await res.text(), {
  columns: true,
  skip_empty_lines: true,
  relax_column_count: true,
});

const url = (v) => {
  const s = String(v ?? "").trim();
  return s.startsWith("https://") ? s : null;
};

const hex = (v) => {
  const s = String(v ?? "").trim();
  return /^#[0-9a-fA-F]{6}$/.test(s) ? s.toUpperCase() : null;
};

const teams = rows
  .map((r) => ({
    abbr: r.team_abbr,
    name: r.team_name,
    nick: r.team_nick,
    primary: hex(r.team_color),
    secondary: hex(r.team_color2),
    logo: url(r.team_logo_espn),
  }))
  .filter((t) => t.abbr && t.primary)
  .sort((a, b) => a.abbr.localeCompare(b.abbr));

const out = `// GENERATED by scripts/build-team-colors.mjs — do not edit by hand.
//
// Official team colours and logo URLs from nflverse-data (teams release).
// Colours go on every table; logos go on scoreboards only, and are hotlinked
// from the source nflverse lists (ESPN's CDN), never served from our domain.
//
// Source and licence: lib/data-source.ts

export type TeamColor = {
  abbr: string;
  name: string;
  nick: string;
  primary: string;
  secondary: string | null;
  /** ESPN-hosted crest, or null when nflverse lists none. */
  logo: string | null;
};

export const TEAM_COLORS: TeamColor[] = [
${teams
  .map(
    (t) =>
      `  ${JSON.stringify({ abbr: t.abbr, name: t.name, nick: t.nick, primary: t.primary, secondary: t.secondary, logo: t.logo })},`,
  )
  .join("\n")}
];
`;

await writeFile("lib/team-colors.generated.ts", out, "utf8");
console.log(`lib/team-colors.generated.ts — ${teams.length} teams`);
