// Bakes lib/team-colors.generated.ts from nflverse's teams release.
//
// Colours only — never logos. Team logos and wordmarks are trademarks, which
// is the same reason the course covers are drawn rather than photographed
// (see CLAUDE.md, Course imagery). A colour swatch beside a three-letter code
// makes a results table read as football without borrowing anyone's mark.
//
// Usage: node scripts/build-team-colors.mjs

import { writeFile } from "node:fs/promises";
import { parse } from "csv-parse/sync";

const URL =
  "https://github.com/nflverse/nflverse-data/releases/download/teams/teams_colors_logos.csv";

const res = await fetch(URL);
if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${URL}`);

const rows = parse(await res.text(), {
  columns: true,
  skip_empty_lines: true,
  relax_column_count: true,
});

const hex = (v) => {
  const s = String(v ?? "").trim();
  return /^#[0-9a-fA-F]{6}$/.test(s) ? s.toUpperCase() : null;
};

const teams = rows
  .map((r) => ({
    abbr: r.team_abbr,
    name: r.team_name,
    nick: r.team_nick,
    primary: hex(r.team_color),
    secondary: hex(r.team_color2),
  }))
  .filter((t) => t.abbr && t.primary)
  .sort((a, b) => a.abbr.localeCompare(b.abbr));

const out = `// GENERATED by scripts/build-team-colors.mjs — do not edit by hand.
//
// Official team colours from nflverse-data (teams release). Colours only:
// logos and wordmarks are trademarks and are deliberately not used anywhere
// in this product.
//
// Source and licence: lib/data-source.ts

export type TeamColor = {
  abbr: string;
  name: string;
  nick: string;
  primary: string;
  secondary: string | null;
};

export const TEAM_COLORS: TeamColor[] = [
${teams
  .map(
    (t) =>
      `  ${JSON.stringify({ abbr: t.abbr, name: t.name, nick: t.nick, primary: t.primary, secondary: t.secondary })},`,
  )
  .join("\n")}
];
`;

await writeFile("lib/team-colors.generated.ts", out, "utf8");
console.log(`lib/team-colors.generated.ts — ${teams.length} teams`);
