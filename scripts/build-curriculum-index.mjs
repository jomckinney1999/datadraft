// Builds two small indexes of the curriculum, for pages that need to know
// about lessons but never play one:
//
//   lib/unit-modules.generated.ts  which course each unit belongs to (the
//                                  Hall of Fame's "different courses" badge)
//   lib/lesson-index.generated.ts  each course's live lessons in order, and
//                                  each lesson's title and blurb (the course
//                                  catalogue, the dashboard's "up next")
//
//   node scripts/build-curriculum-index.mjs
//
// Why: the curriculum is ~560 KB of JavaScript, and the locker chip in the
// nav, the trophy case, /learn and the dashboard all imported it for a count
// or a title. These are a few KB. verify-answer-keys.mjs re-derives both and
// fails if either is stale: rerun this after adding, moving or renaming a
// lesson or a unit.

import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadTs } from "./load-ts.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const c = await loadTs(path.join(root, "lib/curriculum.ts"), root);

/** The rule achievements always used: the first course that lists a unit wins. */
const unitModules = {};
for (const mod of c.MODULES) {
  if (mod.id === c.ALL_MODULE) continue;
  for (const unitId of mod.unitIds) if (!(unitId in unitModules)) unitModules[unitId] = mod.id;
}

/** What liveLessons(moduleId) returns, as ids. */
const liveByModule = {};
for (const mod of c.MODULES) liveByModule[mod.id] = c.liveLessons(mod.id).map((e) => e.lesson.id);
const info = {};
for (const ids of Object.values(liveByModule)) {
  for (const id of ids) {
    if (info[id]) continue;
    const { lesson } = c.getLesson(id);
    info[id] = { title: lesson.title, blurb: lesson.blurb };
  }
}

const HEADER = "// GENERATED by scripts/build-curriculum-index.mjs — do not edit by hand.\n";
const entries = (obj) =>
  Object.entries(obj)
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
    .join("\n");

writeFileSync(
  path.join(root, "lib/unit-modules.generated.ts"),
  `${HEADER}// Which course each unit belongs to (the first course that lists it), so the
// Hall of Fame can count courses without importing the whole curriculum.

export const UNIT_MODULE: Record<string, string> = {
${entries(unitModules)}
};
`,
);
writeFileSync(
  path.join(root, "lib/lesson-index.generated.ts"),
  `${HEADER}// Each course's live lessons in order (what liveLessons(moduleId) returns),
// and each lesson's title and blurb, for pages that list lessons without
// playing one.

export const LIVE_LESSONS: Record<string, string[]> = {
${entries(liveByModule)}
};

export const LESSON_INFO: Record<string, { title: string; blurb: string }> = {
${entries(info)}
};
`,
);
console.log(`units ${Object.keys(unitModules).length}, modules ${Object.keys(liveByModule).length}, lessons ${Object.keys(info).length}`);
