// Builds lib/question-frames.generated.ts: the 2024 week-by-week rows the
// Python and R questions load as `weekly`, and the Excel "Weeks" sheet.
//
//   node scripts/build-question-frames.mjs
//
// Read from lib/lesson-data.generated.ts, the same rows the lesson database
// is seeded from, so a `weekly` total in pandas matches a SUM in SQL to the
// tenth. It's a separate small file so the question bank never pulls the
// whole dataset into a browser bundle. 2024 is a finished season, so the
// weekly data job never changes it; verify-answer-keys.mjs re-checks both
// tables against the database anyway.

import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadTs } from "./load-ts.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const data = await loadTs(path.join(root, "lib/lesson-data.generated.ts"), root);
const excel = await loadTs(path.join(root, "lib/excel-data.ts"), root);

const SEASON = 2024;
const WEEKS = 18;

const rows = data.PACKED_WEEKS.filter((r) => r[3] === SEASON).map(([p, team, position, , week, pts]) => [
  data.PLAYER_NAMES[p],
  position,
  team,
  week,
  pts,
]);
// Week, then points high to low: the first rows anyone prints are five
// different players from week 1, as in the database.
rows.sort((a, b) => a[3] - b[3] || b[4] - a[4] || a[0].localeCompare(b[0]));

// The Weeks sheet follows the Roster sheet's players, in its order, so row 2
// is the same person on both tabs.
const rosterNames = excel.WORKBOOK.Roster.slice(1).map((r) => r[0]);
const header = ["Player", ...Array.from({ length: WEEKS }, (_, i) => `W${i + 1}`)];
const grid = rosterNames.map((name) => {
  const line = [name, ...Array(WEEKS).fill(null)];
  for (const r of rows) if (r[0] === name) line[r[3]] = r[4];
  return line;
});

const out = `// GENERATED by scripts/build-question-frames.mjs — do not edit by hand.
//
// The ${SEASON} regular season, week by week, from the same nflverse rows the
// lesson database is seeded with (lib/lesson-data.generated.ts). The Python
// and R questions load WEEKLY_${SEASON} as \`weekly\`; the Excel questions get
// WEEKS_SHEET_${SEASON} as the "Weeks" tab. Source and licence: lib/data-source.ts

/** One row per game played: [player, position, team, week, points]. Week, then points high to low. */
export const WEEKLY_${SEASON}: [string, string, string, number, number][] = [
${rows.map((r) => `  ${JSON.stringify(r)},`).join("\n")}
];

/** The Roster sheet's ${rosterNames.length} players by week. A blank is a week with no game: a bye, an injury, a benching. */
export const WEEKS_SHEET_${SEASON}: (string | number | null)[][] = [
  ${JSON.stringify(header)},
${grid.map((r) => `  ${JSON.stringify(r)},`).join("\n")}
];
`;

writeFileSync(path.join(root, "lib/question-frames.generated.ts"), out);
console.log(`wrote ${rows.length} weekly rows and a ${grid.length}x${WEEKS} Weeks sheet`);
