// Builds the data behind Roll Call (/questions/roll-call): one row per
// skill player per game of the current regular season, from nflverse's
// `stats_player` weekly release, plus the schedule to say which weeks are
// complete.
//
// Writes the same rows three ways:
//   lib/roll-call-data.generated.ts  — compact, for the server (today's board)
//                                      and the verifier
//   public/roll-call/<season>.json   — expanded, fetched by the browser only
//                                      when someone presses "Run it yourself"
//   public/data/player_weeks_<season>.csv — what the pandas, R and Excel
//                                      answers read
//
// A week is included only once every game in it is final and every team that
// played it has rows in the stats file, so a Friday build never ships a
// "week" of Thursday night alone (the same rule as the lesson data).
//
// Usage: node scripts/build-roll-call-dataset.mjs
// Bump SEASON by hand when a new season starts. The weekly data job reruns it.

import { mkdir, writeFile } from "node:fs/promises";
import { parse } from "csv-parse/sync";

const SEASON = 2026;
const POSITIONS = new Set(["QB", "RB", "WR", "TE"]);
const STATS_URL = `https://github.com/nflverse/nflverse-data/releases/download/stats_player/stats_player_week_${SEASON}.csv`;
const SCHEDULE_URL = "https://raw.githubusercontent.com/nflverse/nfldata/master/data/games.csv";

const num = (v) => {
  if (v === "" || v === undefined || v === "NA") return 0;
  const n = Number(v);
  return Number.isNaN(n) ? 0 : n;
};
const r1 = (x) => Math.round(x * 10) / 10;

async function csv(url) {
  process.stdout.write(`fetching ${url} … `);
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  const rows = parse(await res.text(), { columns: true, skip_empty_lines: true, relax_column_count: true });
  console.log(`${rows.length} rows`);
  return rows;
}

const [stats, schedule] = await Promise.all([csv(STATS_URL), csv(SCHEDULE_URL)]);

// Which weeks are complete: every game final (a game a week past its date
// with no score counts as cancelled), and every team that played has stats.
const today = new Date().toISOString().slice(0, 10);
const weekAgo = new Date(Date.now() - 7 * 864e5).toISOString().slice(0, 10);
const games = schedule.filter((g) => num(g.season) === SEASON && g.game_type === "REG");
const statTeams = new Map();
for (const r of stats) {
  if (r.season_type !== "REG") continue;
  const key = num(r.week);
  if (!statTeams.has(key)) statTeams.set(key, new Set());
  statTeams.get(key).add(r.team);
}
const weekEnds = {};
for (const week of [...new Set(games.map((g) => num(g.week)))].sort((a, b) => a - b)) {
  const inWeek = games.filter((g) => num(g.week) === week);
  const played = inWeek.filter((g) => String(g.result ?? "").trim() !== "" && g.result !== "NA");
  const cancelled = inWeek.filter((g) => !played.includes(g) && g.gameday < weekAgo);
  if (played.length + cancelled.length < inWeek.length || played.length === 0) break;
  const teams = statTeams.get(week) ?? new Set();
  const missing = played.flatMap((g) => [g.home_team, g.away_team]).filter((t) => !teams.has(t));
  if (missing.length) {
    console.log(`week ${week}: games final but no stats yet for ${missing.join(", ")}; stopping here`);
    break;
  }
  weekEnds[week] = played.map((g) => g.gameday).sort().pop();
}
const weeks = Object.keys(weekEnds).map(Number);
console.log(`${SEASON}: complete weeks ${weeks.join(", ") || "none"} (built ${today})`);

const players = {};
const rows = [];
for (const r of stats) {
  if (r.season_type !== "REG" || !POSITIONS.has(r.position)) continue;
  const week = num(r.week);
  if (!(week in weekEnds)) continue;
  players[r.player_id] ??= [r.player_display_name, r.position, r.headshot_url && r.headshot_url !== "NA" ? r.headshot_url : ""];
  rows.push([
    r.player_id,
    r.team,
    r.opponent_team,
    week,
    num(r.passing_yards),
    num(r.passing_tds),
    num(r.rushing_yards),
    num(r.rushing_tds),
    num(r.receptions),
    num(r.receiving_yards),
    num(r.receiving_tds),
    r1(num(r.fantasy_points_ppr)),
  ]);
}
// Stable order: week, then team, then player, so a rebuild with nothing new
// writes the same file.
rows.sort((a, b) => a[3] - b[3] || a[1].localeCompare(b[1]) || a[0].localeCompare(b[0]));

const ts = `// Generated by scripts/build-roll-call-dataset.mjs — do not edit by hand.
// Real ${SEASON} regular-season weekly stats for QB/RB/WR/TE from nflverse
// (CC BY 4.0), complete weeks only.

export const ROLL_CALL_SEASON = ${SEASON};

/** Each complete week's last game day, YYYY-MM-DD. */
export const ROLL_CALL_WEEK_ENDS: Record<number, string> = ${JSON.stringify(weekEnds)};

/** player_id → [name, position, headshot URL or ""] */
export const ROLL_CALL_PLAYERS: Record<string, [string, string, string]> = {
${Object.entries(players)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([id, p]) => `  ${JSON.stringify(id)}: ${JSON.stringify(p)},`)
  .join("\n")}
};

/**
 * [player_id, team, opponent, week, passing_yards, passing_tds, rushing_yards,
 *  rushing_tds, receptions, receiving_yards, receiving_tds, fantasy_points_ppr]
 */
export type RollCallRow = [string, string, string, number, number, number, number, number, number, number, number, number];

export const ROLL_CALL_ROWS: RollCallRow[] = [
${rows.map((r) => `  ${JSON.stringify(r)},`).join("\n")}
];
`;
await writeFile("lib/roll-call-data.generated.ts", ts);

const columns = [
  "player_id",
  "player",
  "position",
  "team",
  "opponent",
  "season",
  "week",
  "passing_yards",
  "passing_tds",
  "rushing_yards",
  "rushing_tds",
  "receptions",
  "receiving_yards",
  "receiving_tds",
  "fantasy_points_ppr",
];
const expanded = rows.map(([id, team, opp, week, ...nums]) => [id, players[id][0], players[id][1], team, opp, SEASON, week, ...nums]);
await mkdir("public/roll-call", { recursive: true });
await writeFile(`public/roll-call/${SEASON}.json`, JSON.stringify({ season: SEASON, columns, rows: expanded }));
// The same table as a CSV, which the pandas, R and Excel versions of every
// Roll Call answer read (lib/roll-call.ts, PLAYER_WEEKS_CSV).
const cell = (v) => (typeof v === "string" && /[",\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : String(v));
await writeFile(
  `public/data/player_weeks_${SEASON}.csv`,
  [columns.join(","), ...expanded.map((r) => r.map(cell).join(","))].join("\n") + "\n",
);
console.log(`wrote ${rows.length} rows, ${Object.keys(players).length} players`);
